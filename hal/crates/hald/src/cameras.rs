//! Stable camera names. USB cameras enumerate as `/dev/videoN` in whatever
//! order they come up, so upper and lower can swap across reboots. Each UVC
//! camera also exposes a metadata node next to its capture node. We pin each
//! camera to its physical USB port with udev rules that only match the
//! capture node (`index == 0`), giving `/dev/seedypod/camera-<name>`.

use std::path::{Path, PathBuf};

use serde::Serialize;

/// A capture node found in sysfs.
#[derive(Debug, Clone, PartialEq, Serialize)]
pub struct Detected {
    /// `/dev/videoN` today; only the port is stable.
    pub device: PathBuf,
    pub name: String,
    /// The USB interface the camera hangs off, e.g. `1-1.2:1.0` (udev `KERNELS`).
    pub port: String,
}

/// Capture nodes (`index` 0) under `<sysfs>/class/video4linux`, sorted by port.
pub fn discover(sysfs: &Path, dev: &Path) -> Vec<Detected> {
    let Ok(entries) = std::fs::read_dir(sysfs.join("class/video4linux")) else {
        return Vec::new();
    };
    let mut out: Vec<Detected> = entries
        .flatten()
        .filter_map(|e| {
            let node = e.path();
            let read = |f: &str| {
                std::fs::read_to_string(node.join(f))
                    .ok()
                    .map(|s| s.trim().to_owned())
            };
            if read("index").as_deref() != Some("0") {
                return None;
            }
            let port = std::fs::canonicalize(node.join("device"))
                .ok()?
                .file_name()?
                .to_string_lossy()
                .into_owned();
            Some(Detected {
                device: dev.join(e.file_name()),
                name: read("name").unwrap_or_default(),
                port,
            })
        })
        .collect();
    out.sort_by_key(|d| port_key(&d.port));
    out
}

/// Sort ports numerically (`1-1.10` after `1-1.9`).
fn port_key(port: &str) -> Vec<u32> {
    port.split(|c: char| !c.is_ascii_digit())
        .filter_map(|n| n.parse().ok())
        .collect()
}

/// Default assignment: the first two cameras by port become `upper` and `lower`.
pub fn default_assignment(found: &[Detected]) -> Vec<(String, String)> {
    ["upper", "lower"]
        .iter()
        .zip(found)
        .map(|(name, d)| ((*name).to_owned(), d.port.clone()))
        .collect()
}

/// Parse `upper=1-1.2:1.0` pairs from the command line.
pub fn parse_assignment(args: &[String]) -> Result<Vec<(String, String)>, String> {
    args.iter()
        .map(|a| {
            let (name, port) = a
                .split_once('=')
                .ok_or_else(|| format!("expected NAME=PORT, got {a:?}"))?;
            let ok_name = !name.is_empty()
                && name
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');
            let ok_port = !port.is_empty()
                && port
                    .chars()
                    .all(|c| c.is_ascii_alphanumeric() || "-.:".contains(c));
            if !ok_name || !ok_port {
                return Err(format!("bad camera assignment {a:?}"));
            }
            Ok((name.to_owned(), port.to_owned()))
        })
        .collect()
}

/// The udev rules file for an assignment.
pub fn rules(assign: &[(String, String)]) -> String {
    let mut s = String::from(
        "# Stable names for the seedypod cameras, by USB port. Generated by `hald --camera-rules`.\n\
         # Capture node only: each UVC camera also has a metadata node that must not take the name.\n",
    );
    for (name, port) in assign {
        s.push_str(&format!(
            "SUBSYSTEM==\"video4linux\", KERNELS==\"{port}\", ATTR{{index}}==\"0\", SYMLINK+=\"seedypod/camera-{name}\"\n"
        ));
    }
    s
}

/// `/dev/seedypod/camera-<name>`, the stable path the rules create.
pub fn stable_path(name: &str) -> PathBuf {
    PathBuf::from(format!("/dev/seedypod/camera-{name}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// A fake sysfs: two cameras, each with a capture and a metadata node, plus one unplugged entry.
    fn fake_sysfs(tag: &str) -> PathBuf {
        let root = std::env::temp_dir().join(format!("hald-cameras-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let class = root.join("class/video4linux");
        for (node, index, port, name) in [
            ("video0", "0", "1-1.3:1.0", "Lower Cam"),
            ("video1", "1", "1-1.3:1.0", "Lower Cam"),
            ("video2", "0", "1-1.2:1.0", "Upper Cam"),
            ("video3", "1", "1-1.2:1.0", "Upper Cam"),
            ("video9", "0", "1-1.10:1.0", "Spare"),
        ] {
            let iface = root.join("devices/platform/usb1/1-1").join(port);
            std::fs::create_dir_all(&iface).unwrap();
            let dir = class.join(node);
            std::fs::create_dir_all(&dir).unwrap();
            std::fs::write(dir.join("index"), format!("{index}\n")).unwrap();
            std::fs::write(dir.join("name"), format!("{name}\n")).unwrap();
            #[cfg(unix)]
            std::os::unix::fs::symlink(&iface, dir.join("device")).unwrap();
        }
        // A node whose device link is gone (unplugged mid-enumeration) is skipped.
        let gone = class.join("video7");
        std::fs::create_dir_all(&gone).unwrap();
        std::fs::write(gone.join("index"), "0\n").unwrap();
        root
    }

    #[test]
    fn finds_capture_nodes_by_port_and_skips_metadata_nodes() {
        let root = fake_sysfs("discover");
        let found = discover(&root, Path::new("/dev"));
        assert_eq!(
            found
                .iter()
                .map(|d| (d.device.display().to_string(), d.port.as_str(), d.name.as_str()))
                .collect::<Vec<_>>(),
            vec![
                ("/dev/video2".to_string(), "1-1.2:1.0", "Upper Cam"),
                ("/dev/video0".to_string(), "1-1.3:1.0", "Lower Cam"),
                ("/dev/video9".to_string(), "1-1.10:1.0", "Spare"),
            ]
        );
        assert_eq!(
            default_assignment(&found),
            vec![
                ("upper".into(), "1-1.2:1.0".into()),
                ("lower".into(), "1-1.3:1.0".into())
            ]
        );
        assert!(discover(&root.join("nope"), Path::new("/dev")).is_empty());
        let _ = std::fs::remove_dir_all(root);
    }

    #[test]
    fn rules_pin_names_to_ports_on_the_capture_node_only() {
        let r = rules(&[
            ("upper".into(), "1-1.2:1.0".into()),
            ("lower".into(), "1-1.3:1.0".into()),
        ]);
        assert!(r.contains(
            "SUBSYSTEM==\"video4linux\", KERNELS==\"1-1.2:1.0\", ATTR{index}==\"0\", SYMLINK+=\"seedypod/camera-upper\"\n"
        ));
        assert!(r.contains("KERNELS==\"1-1.3:1.0\", ATTR{index}==\"0\", SYMLINK+=\"seedypod/camera-lower\""));
        assert_eq!(r.lines().filter(|l| l.starts_with("SUBSYSTEM")).count(), 2);
        assert_eq!(stable_path("upper"), PathBuf::from("/dev/seedypod/camera-upper"));
    }

    #[test]
    fn assignments_are_validated() {
        assert_eq!(
            parse_assignment(&["upper=1-1.3:1.0".into(), "lower=1-1.2:1.0".into()]).unwrap(),
            vec![
                ("upper".into(), "1-1.3:1.0".into()),
                ("lower".into(), "1-1.2:1.0".into())
            ]
        );
        assert!(parse_assignment(&["upper".into()]).is_err());
        assert!(parse_assignment(&["upper=1-1\"; RUN+=\"/bin/sh".into()]).is_err());
        assert!(parse_assignment(&["=1-1.2:1.0".into()]).is_err());
    }
}
